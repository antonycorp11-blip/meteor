function glyph(ch: string): string {
  let c = ch.toUpperCase();
  c = ACCENTS[c] ?? c;
  return G[c] ?? G['?'];
}

export function textWidth(text: string, scale = 1) {
  return text.length * 6 * scale - scale;
}

/** Desenha texto com retângulos de 1px (nítido em qualquer canvas). */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow: string | null = '#0B1026',
) {
  x = Math.round(x);
  y = Math.round(y);
  const draw = (ox: number, oy: number, col: string) => {
    ctx.fillStyle = col;
    let cx = x + ox;
    for (const ch of text) {
      const g = glyph(ch);
      for (let i = 0; i < 35; i++) {
        if (g[i] === '1') ctx.fillRect(cx + (i % 5) * scale, y + oy + Math.floor(i / 5) * scale, scale, scale);
      }
      cx += 6 * scale;
    }
  };
  if (shadow) draw(scale, scale, shadow);
  draw(0, 0, color);
}

/** Gera um canvas com o texto em pixel, para uso em DOM (títulos). */
export function pixelTitle(text: string, scale: number, color: string, shadow = '#0B1026'): HTMLCanvasElement {
  const c = document.createElement('canvas');
  c.width = textWidth(text, scale) + scale * 2;
  c.height = 7 * scale + scale * 2;
  const ctx = c.getContext('2d')!;
  drawPixelText(ctx, text, 0, 0, color, scale, shadow);
  return c;
}
